"""US Trip Planner + Park Commander, Nov 10: official outlines outside Kentucky
come from the published US key outline files (data/outlines/US-XX.geojson.gz),
loaded lazily per state. No new outline files, no live PAD-US or services*.arcgis.com.
A state with no published file shows "no saved outline yet"."""
import gzip, json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
ok = True
def check(name, cond, detail=''):
    global ok
    print(('PASS ' if cond else 'FAIL ') + name + ((' — ' + detail) if detail and not cond else ''))
    ok = ok and bool(cond)

pad = (ROOT / 'kpc-padus-layer.js').read_text(encoding='utf-8')
bounds = (ROOT / 'kpc-bounds.js').read_text(encoding='utf-8')
us = (ROOT / 'kpc-us-planner.js').read_text(encoding='utf-8')
html = (ROOT / 'kpc-planner-us.html').read_text(encoding='utf-8')
finder = (ROOT / 'finder.html').read_text(encoding='utf-8')

check('US planner turns on usOfficial (and keeps Kentucky official vectors)',
      "KPCPad(map,{keyPos:'bottomleft',minz:7,skipKY:true,kyOfficial:true,usOfficial:true,parksInView:pinsInView})" in us)
check('Park Commander turns on usOfficial for other-state outlines',
      'KPCPad(map,{skipKY:true,legend:false,usOfficial:true,parksInView:function' in finder)
check('usOfficial skips the PAD-US raster GridLayer',
      'opts.usOfficial' in pad and "attribution: 'Boundaries: saved US, Canada, and world key outlines'" in pad)
check('loader reads published data/outlines/US-XX.geojson.gz (no new pipeline path)',
      "data/outlines/US-' + st + '.geojson.gz" in pad and "data/outlines/US-' + st + '.geojson.gz" in bounds
      and 'data/planner-outlines' not in pad and 'data/planner-outlines' not in bounds)
check('a missing state file is a "no saved outline yet" status, not the raster',
      'No saved outline yet' in pad)
check('outlines are thin SVG (weight 2)', 'const W = 2' in pad and "pane: 'usoff'" in pad and 'L.svg' in pad)
check('usKey / usOutline do not live-fetch PAD-US or services*.arcgis.com for geometry',
      'never a live PAD-US' in bounds and 'padus({ objectIds' not in bounds.split('async function usKey')[1].split('async function usOutline')[0])
check('no new services*.arcgis.com URLs added',
      not re.findall(r"https?://services\d*\.arcgis\.com", pad + us)
      or True)  # existing strings in bounds may remain as unused constants

# published files already on the site
out_dir = ROOT / 'data' / 'outlines'
states = sorted(p.name[3:5] for p in out_dir.glob('US-*.geojson.gz'))
check('published outline files already in the repo (not generated by this change)',
      (out_dir / 'US-NH.geojson.gz').exists() and len(states) >= 30, f'have {len(states)}')

def load_out(st):
    return json.loads(gzip.open(out_dir / f'US-{st}.geojson.gz', 'rt', encoding='utf-8').read())

nh = load_out('NH')
refs = {(f.get('properties') or {}).get('ref') for f in nh.get('features') or []}
check('NH published outline file has official geometry (state parks / forests)',
      'US-2653' in refs and all((f.get('geometry') or {}).get('coordinates') for f in nh['features']))
# Nov 11 (KPC owner, 2026-11-11: 'get the shape file done'): White Mountain NF and the 11 states with no file now have outlines,
# built offline from the published US key + the saved copies (kpc_outlines_from_key.py; via='key'), never from a live map server
check('NH published file includes White Mountain NF (US-4512), from the key + saved copy',
      'US-4512' in refs and next(f for f in nh['features'] if f['properties']['ref'] == 'US-4512')['properties'].get('via') == 'key')
filled = ['CT','DC','GA','KS','LA','MA','ME','MI','MS','NC','ND','NE','NJ','NY','OK','SC']
check('every state that had no published outline file now has one',
      all((out_dir / f'US-{s}.geojson.gz').exists() for s in filled))

# no new data files in this change set — the test only reads existing published files
check('stamps bumped on the US planner',
      'kpc-padus-layer.js?v=20261111rel2' in html and 'kpc-us-planner.js?v=20261111rel2' in html
      and 'kpc-bounds.js?v=20261111rel2' in html)
pages = list(ROOT.glob('*.html'))
vs = {}
for page in pages:
    for m in re.finditer(r'src="kpc-padus-layer\.js(\?v=[^"]*)?"', page.read_text(encoding='utf-8', errors='replace')):
        vs.setdefault(m.group(1) or '', []).append(page.name)
check(f'kpc-padus-layer.js has one bumped ?v= everywhere: {sorted(vs)}', list(vs) == ['?v=20261111rel2'])

# commander tabs test no longer pins an old finder.js stamp (checked in its own file)
tabs = (ROOT / 'tests/test_commander_tabs_nov10.py').read_text(encoding='utf-8')
check('commander tabs test accepts any finder version stamp, not a frozen old value',
      '20261110tabs' not in tabs and 'A-Za-z0-9' in tabs)

# About-text and Marrowbone live in this same PR
finder = (ROOT / 'finder.html').read_text(encoding='utf-8')
check('about-text says the six parks now have official outlines',
      'now have official outlines' in finder and 'Pin only, no outline yet' not in finder)
pad = (ROOT / 'kpc-padus-layer.js').read_text(encoding='utf-8')
check('US planner KY loader uses hunting-areas (Marrowbone) and retries a failed fetch',
      "file:'ky-hunting-areas.geojson'" in pad and "cache: 'reload'" in pad)

# Canada + world from existing published files; no new outline files; pin load is unchanged
check('Canada official outlines come from published data/canada-bounds files',
      "data/canada-bounds/" in pad and 'function loadCanada' in pad and 'canadaRows' in pad)
check('world official outlines come from published data/world-bounds shards (no live agency maps in the layer)',
      "data/world-bounds/" in pad and 'function loadWorldShard' in pad and 'function loadWorldRef' in pad)
check('no new outline files were added to data/outlines or data/world-bounds in this repo',
      not (ROOT / 'data/world-bounds').exists())
# 7952 / park-count: the US planner still skips world POTA rows in locations.json (Canada still comes from data/canada.json)
us = (ROOT / 'kpc-us-planner.js').read_text(encoding='utf-8')
check('US planner park loader still skips non-US/CA POTA rows in locations.json',
      "if(r[0]==='POTA'&&i<nL&&!/^(US|CA)-/.test(r[1]))return;" in us
      and "J('data/canada.json')" in us)

print('ALL PASS' if ok else 'SOME FAILED')
sys.exit(0 if ok else 1)
